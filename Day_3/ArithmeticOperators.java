public class ArithmeticOperators{
    public static void main(String [] args){
        int a=28;
        int b=15;
        System.out.println("a: " + a);
        System.out.println("b: " + b);

        System.out.println("====Arithmetic Operators====\n");
        System.out.println("(a+b): " + (a+b));
        System.out.println("(a-b): " + (a-b));
        System.out.println("(a*b): " + (a*b));
        System.out.println("(a/b): " + (a/b));
        System.out.println("(a%b): " + (a%b));

    }
}